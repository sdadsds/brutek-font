function getSidebearings(char) {
  if (CUSTOM_SB[char]) return CUSTOM_SB[char];
  // Base-letter fallback for accented characters
  const norm = char.normalize('NFD')[0];
  if (CUSTOM_SB[norm]) return CUSTOM_SB[norm];
  return [18, 18];
}

